"""Regenerate seed.sql from seed_data.json.

Usage:  python database/generate_seed.py
Edit seed_data.json (the single source of truth for the catalog), then run this.
"""
import json
from pathlib import Path

HERE = Path(__file__).parent


def q(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def main():
    data = json.loads((HERE / "seed_data.json").read_text(encoding="utf-8"))
    out = [
        "-- ---------------------------------------------------------------------------",
        "-- Vision Project Atlas : seed (the catalog)",
        "--",
        "-- Generated by generate_seed.py from seed_data.json. Do not edit by hand:",
        "-- edit seed_data.json and run  python database/generate_seed.py",
        "--",
        "-- Mounted into /docker-entrypoint-initdb.d/ after schema.sql, so a fresh",
        "-- volume starts with all 90 projects. Load it by hand into an existing",
        "-- database with:",
        "--",
        "--   docker compose exec -T postgres psql -U atlas -d atlas < database/seed.sql",
        "--",
        "-- Safe to re-run: every insert is ON CONFLICT DO NOTHING.",
        "-- ---------------------------------------------------------------------------",
        "",
        "BEGIN;",
        "",
    ]

    out.append("-- ===== DOMAINS =====")
    for d in data["domains"]:
        out.append(f"INSERT INTO domain (code, name, slug) VALUES ({q(d['code'])}, {q(d['name'])}, {q(d['slug'])}) ON CONFLICT (code) DO NOTHING;")

    out += ["", "-- ===== TASK TYPES AND THEIR BUILD STEPS ====="]
    for t in data["task_types"]:
        out.append(f"INSERT INTO task_type (code, name, metric) VALUES ({q(t['code'])}, {q(t['name'])}, {q(t['metric'])}) ON CONFLICT (code) DO NOTHING;")
        for i, step in enumerate(t["steps"], start=1):
            out.append(
                "INSERT INTO task_step (task_type_id, position, text) "
                f"SELECT id, {i}, {q(step)} FROM task_type WHERE code = {q(t['code'])} ON CONFLICT DO NOTHING;"
            )

    techs = sorted({t for p in data["projects"] for t in p["technologies"]}, key=str.lower)
    out += ["", "-- ===== TECHNOLOGIES ====="]
    for t in techs:
        out.append(f"INSERT INTO technology (name) VALUES ({q(t)}) ON CONFLICT (name) DO NOTHING;")

    out += ["", "-- ===== PROJECTS ====="]
    for p in data["projects"]:
        out.append(
            "INSERT INTO project (id, title, slug, description, domain_id, task_type_id, level, is_pick, pick_reason, caution, lab) "
            f"SELECT {p['id']}, {q(p['title'])}, {q(p['slug'])}, {q(p['description'])}, d.id, t.id, {p['level']}, "
            f"{q(p['is_pick'])}, {q(p['pick_reason'])}, {q(p['caution'])}, "
            f"{q(json.dumps(p['lab'], ensure_ascii=False)) + '::jsonb' if p.get('lab') else 'NULL'} "
            f"FROM domain d, task_type t WHERE d.code = {q(p['domain'])} AND t.code = {q(p['task_type'])} "
            "ON CONFLICT (id) DO NOTHING;"
        )
        for i, tech in enumerate(p["technologies"]):
            out.append(
                "INSERT INTO project_technology (project_id, technology_id, position) "
                f"SELECT {p['id']}, id, {i} FROM technology WHERE name = {q(tech)} ON CONFLICT DO NOTHING;"
            )

    out += ["", "-- Keep the id sequence ahead of the seeded ids",
            "SELECT setval(pg_get_serial_sequence('project', 'id'), (SELECT MAX(id) FROM project));",
            "", "COMMIT;", ""]
    (HERE / "seed.sql").write_text("\n".join(out), encoding="utf-8")
    print(f"seed.sql written: {len(data['projects'])} projects, {len(techs)} technologies")


if __name__ == "__main__":
    main()
